"""Generate exact native authority for Home's existing Wi-Fi namespace access."""
import argparse,json
from pathlib import Path
p=argparse.ArgumentParser()
for n in ('baseline','candidate','output'):p.add_argument('--'+n,type=Path,required=True)
a=p.parse_args()
before=json.loads((a.baseline/'boot.json').read_text())
after=json.loads((a.candidate/'boot.json').read_text())
old=json.loads((a.baseline/'cohort.json').read_text());new=json.loads((a.candidate/'cohort.json').read_text())
assert old['version']=='1.1.33' and new['version']=='1.1.34'
assert old['source_repo']==new['source_repo'] and old['product']==new['product']
def identity(c):return '{'+','.join(json.dumps(c[k]) for k in ('product','version','source_repo','source_revision','runtime_version'))+'}'
matching=lambda g:g['capability']=='storage.key-value' and g['api']==1 and g['instance_id']==6
owners=[]
for policy in before['app_capabilities']:
 if any(matching(g) for g in policy['grants']):owners.append(json.loads((a.baseline/policy['manifest']).read_text())['id'])
assert owners and 'twatch-clock' not in owners
home=next(p for p in after['app_capabilities'] if p['manifest']=='default.json')
assert sum(matching(g) for g in home['grants'])==1
assert json.loads((a.candidate/'default.json').read_text())['id']=='twatch-clock'
compact=lambda v:json.dumps(v,separators=(',',':'))
text='''#pragma once
// Generated by scripts/generate_provision_migration.py from exact cohort snapshots.
#include "runtime/update/NativeAppDataExportPolicyV2.h"
namespace RiscUpdate {
static constexpr const char* t023WifiOwners[]={OWNERS};
static constexpr NativeSharedKeyValueV2 t023WifiSharing[]={
 {"twatch-clock",1,6,t023WifiOwners,sizeof(t023WifiOwners)/sizeof(t023WifiOwners[0])}};
inline constexpr NativeAppDataExportPolicyV2 selectedNativeAppDataExportPolicyV2() {
 return {2,"watch-t023-home-wifi-133-134",FROM,TO,
 BEFORE,AFTER,t023WifiSharing,1};
}
}
'''
for key,value in {'OWNERS':','.join(map(json.dumps,owners)),'FROM':identity(old),'TO':identity(new),'BEFORE':json.dumps(compact(before['app_capabilities'])),'AFTER':json.dumps(compact(after['app_capabilities']))}.items():text=text.replace(key,value)
a.output.write_text(text)
print('Exact Wi-Fi namespace sharing owners:',owners)
